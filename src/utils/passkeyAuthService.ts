// Helpers to convert ArrayBuffer to Base64URL and vice-versa
export function bufferToBase64url(buffer: ArrayBuffer | Uint8Array): string {
  const bytes = buffer instanceof Uint8Array ? buffer : new Uint8Array(buffer);
  let binary = '';
  for (let i = 0; i < bytes.byteLength; i++) {
    binary += String.fromCharCode(bytes[i]);
  }
  return btoa(binary)
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');
}

export function base64urlToBuffer(base64url: string): ArrayBuffer {
  const base64 = base64url
    .replace(/-/g, '+')
    .replace(/_/g, '/');
  const padLen = (4 - (base64.length % 4)) % 4;
  const padded = base64 + '='.repeat(padLen);
  const binary = atob(padded);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i);
  }
  return bytes.buffer;
}

/**
 * Check if the browser environment supports WebAuthn / Passkeys
 */
export function isPasskeySupported(): boolean {
  if (typeof window === 'undefined') return false;
  return !!(
    window.PublicKeyCredential &&
    navigator.credentials &&
    typeof navigator.credentials.create === 'function' &&
    typeof navigator.credentials.get === 'function'
  );
}

/**
 * Check if biometric / device lock authenticator (TouchID, FaceID, Windows Hello, Phone) is available
 */
export async function isBiometricPasskeyAvailable(): Promise<boolean> {
  if (!isPasskeySupported()) return false;
  try {
    if (typeof PublicKeyCredential.isUserVerifyingPlatformAuthenticatorAvailable === 'function') {
      return await PublicKeyCredential.isUserVerifyingPlatformAuthenticatorAvailable();
    }
  } catch {
    return false;
  }
  return true;
}

export interface RegisterPasskeyParams {
  email: string;
  firstName: string;
  lastName: string;
  username: string; // pseudo
}

export interface RegisterEmailParams {
  email: string;
  password: string;
  firstName?: string;
  lastName?: string;
  username: string; // pseudo
}

/**
 * Register a new user with WebAuthn Passkey generated by device / smartphone
 */
export async function registerWithPasskey(
  params: RegisterPasskeyParams
): Promise<{ success: boolean; user?: SynapseUser; message?: string; error?: string }> {
  try {
    if (!isPasskeySupported()) {
      return {
        success: false,
        message: 'Votre navigateur ou appareil ne supporte pas l\'authentification par Passkey.',
        error: 'Passkeys not supported',
      };
    }

    const cleanEmail = params.email.trim().toLowerCase();
    const cleanFirstName = params.firstName.trim();
    const cleanLastName = params.lastName.trim();
    const cleanUsername = params.username.trim() || cleanEmail.split('@')[0];
    const displayName = `${cleanFirstName} ${cleanLastName}`.trim() || cleanUsername;

    if (!cleanEmail || !cleanEmail.includes('@')) {
      return { success: false, message: 'Veuillez saisir une adresse e-mail valide.' };
    }
    if (!cleanUsername) {
      return { success: false, message: 'Veuillez choisir un pseudo.' };
    }

    // Generate random 32-byte challenge
    const challenge = new Uint8Array(32);
    window.crypto.getRandomValues(challenge);

    // User ID buffer (derived from email or random)
    const userIdBuffer = new TextEncoder().encode(cleanEmail);

    // Relying Party identifier (hostname)
    const rpId = window.location.hostname;

    const publicKeyCredentialCreationOptions: PublicKeyCredentialCreationOptions = {
      challenge: challenge.buffer,
      rp: {
        name: 'Radio Synapse',
        id: rpId === 'localhost' ? undefined : rpId,
      },
      user: {
        id: userIdBuffer,
        name: cleanEmail,
        displayName: `${displayName} (@${cleanUsername})`,
      },
      pubKeyCredParams: [
        { alg: -7, type: 'public-key' },  // ES256
        { alg: -257, type: 'public-key' }, // RS256
      ],
      authenticatorSelection: {
        authenticatorAttachment: undefined, // Allows phone, USB, platform (cross-platform or platform)
        userVerification: 'preferred',
        residentKey: 'preferred',
        requireResidentKey: false,
      },
      timeout: 60000,
      attestation: 'none',
    };

    // Prompt user device (Fingerprint / Face ID / Phone QR scan / PIN)
    const credential = (await navigator.credentials.create({
      publicKey: publicKeyCredentialCreationOptions,
    })) as PublicKeyCredential | null;

    if (!credential) {
      return {
        success: false,
        message: 'La création de la Passkey a été annulée ou n\'a pas pu aboutir.',
      };
    }

    const credentialId = credential.id;
    const rawIdBase64 = bufferToBase64url(credential.rawId);

    // Determine user role
    const isSuper = cleanEmail === 'adminradiosynapse@gmail.com' || cleanEmail === 'admin@radiosynapse.fr';
    const role: UserRole = isSuper ? 'super-admin' : 'user';
    const userId = `usr_${Date.now()}_${Math.random().toString(36).substring(2, 9)}`;

    const synapseUser: SynapseUser = {
      id: userId,
      email: cleanEmail,
      username: cleanUsername,
      firstName: cleanFirstName,
      lastName: cleanLastName,
      displayName: displayName,
      role: role,
      adminProfileId: isSuper ? 'profile_super_admin' : 'profile_animateur',
      assignedStationId: 'all',
      avatarUrl: `https://api.dicebear.com/7.x/bottts/svg?seed=${encodeURIComponent(cleanUsername)}`,
      createdAt: Date.now(),
      points: 150, // Bonus points for passkey registration
      badges: ['Passkey Sécurisée', 'Pionnier Biométrique'],
      authMethod: 'passkey',
      passkeyCredentialId: credentialId,
      passkeyCreatedAt: Date.now(),
    };

    // Save to local storage
    saveStoredSynapseUser(synapseUser);

    // Persist to Supabase profiles & synapse_passkeys
    try {
      await supabase.from('profiles').upsert({
        id: synapseUser.id,
        email: cleanEmail,
        first_name: cleanFirstName,
        last_name: cleanLastName,
        username: cleanUsername,
        display_name: displayName,
        role: role,
        avatar_url: synapseUser.avatarUrl,
        points: synapseUser.points,
        badges: synapseUser.badges,
        auth_method: 'passkey',
        passkey_credential_id: credentialId,
        passkey_public_key: rawIdBase64,
        passkey_created_at: new Date().toISOString(),
        updated_at: new Date().toISOString(),
      }, { onConflict: 'email' });

      // Also record in synapse_passkeys table
      await supabase.from('synapse_passkeys').insert({
        user_id: synapseUser.id,
        email: cleanEmail,
        credential_id: credentialId,
        public_key: rawIdBase64,
        device_name: 'Passkey Smartphone / Appareil',
        created_at: new Date().toISOString(),
      });
    } catch (dbErr) {
      console.warn('Supabase passkey sync notice:', dbErr);
    }

    return {
      success: true,
      user: synapseUser,
      message: `Compte créé et Passkey liée avec succès pour ${cleanUsername} !`,
    };
  } catch (err: any) {
    console.error('Passkey creation error:', err);
    if (err.name === 'NotAllowedError') {
      return { success: false, message: 'Création de la Passkey refusée ou annulée par l\'utilisateur.' };
    }
    return { success: false, message: err?.message || 'Erreur lors de la création de la Passkey.', error: err?.message };
  }
}

/**
 * Login with a previously registered Passkey (Phone, Biometric, Windows Hello, Touch ID, Face ID)
 */
export async function loginWithPasskey(
  emailHint?: string
): Promise<{ success: boolean; user?: SynapseUser; message?: string; error?: string }> {
  try {
    if (!isPasskeySupported()) {
      return {
        success: false,
        message: 'Votre navigateur ou appareil ne supporte pas l\'authentification par Passkey.',
        error: 'Passkeys not supported',
      };
    }

    // Generate random 32-byte challenge
    const challenge = new Uint8Array(32);
    window.crypto.getRandomValues(challenge);

    const rpId = window.location.hostname;

    // Optional: allowCredentials if email or stored user has a known credential ID
    let allowCredentials: PublicKeyCredentialDescriptor[] | undefined = undefined;
    const storedUser = getStoredSynapseUser();

    if (storedUser?.passkeyCredentialId) {
      try {
        allowCredentials = [
          {
            id: base64urlToBuffer(storedUser.passkeyCredentialId),
            type: 'public-key',
          },
        ];
      } catch {}
    }

    const publicKeyCredentialRequestOptions: PublicKeyCredentialRequestOptions = {
      challenge: challenge.buffer,
      rpId: rpId === 'localhost' ? undefined : rpId,
      allowCredentials: allowCredentials,
      userVerification: 'preferred',
      timeout: 60000,
    };

    // Prompt user biometric / phone
    const assertion = (await navigator.credentials.get({
      publicKey: publicKeyCredentialRequestOptions,
    })) as PublicKeyCredential | null;

    if (!assertion) {
      return {
        success: false,
        message: 'Connexion par Passkey annulée.',
      };
    }

    const usedCredentialId = assertion.id;

    // Check if stored user matches or query Supabase
    let matchedUser: SynapseUser | null = null;

    if (storedUser && (storedUser.passkeyCredentialId === usedCredentialId || !emailHint || storedUser.email.toLowerCase() === emailHint.toLowerCase())) {
      matchedUser = storedUser;
    }

    // Query Supabase profiles by passkey_credential_id or email
    if (!matchedUser) {
      try {
        let query = supabase.from('profiles').select('*');
        if (emailHint) {
          query = query.eq('email', emailHint.trim().toLowerCase());
        } else {
          query = query.eq('passkey_credential_id', usedCredentialId);
        }

        const { data: profile } = await query.maybeSingle();

        if (profile) {
          const cleanEmail = (profile.email || '').trim().toLowerCase();
          const isSuper = cleanEmail === 'adminradiosynapse@gmail.com' || cleanEmail === 'admin@radiosynapse.fr' || profile.role === 'super-admin';
          matchedUser = {
            id: profile.id,
            email: cleanEmail,
            username: profile.username || profile.display_name || cleanEmail.split('@')[0],
            firstName: profile.first_name,
            lastName: profile.last_name,
            displayName: profile.display_name || `${profile.first_name || ''} ${profile.last_name || ''}`.trim() || profile.username,
            role: isSuper ? 'super-admin' : (profile.role || 'user'),
            adminProfileId: profile.admin_profile_id || (isSuper ? 'profile_super_admin' : 'profile_animateur'),
            assignedStationId: profile.assigned_station_id || 'all',
            avatarUrl: profile.avatar_url,
            createdAt: new Date(profile.created_at || Date.now()).getTime(),
            points: profile.points ?? 100,
            badges: profile.badges || ['Passkey Sécurisée'],
            authMethod: 'passkey',
            passkeyCredentialId: usedCredentialId,
          };
        }
      } catch (dbErr) {
        console.warn('DB lookup error for passkey:', dbErr);
      }
    }

    // Fallback if no matching record found in Supabase yet
    if (!matchedUser) {
      const fallbackEmail = emailHint?.trim().toLowerCase() || storedUser?.email || 'auditeur@radiosynapse.fr';
      const isSuper = fallbackEmail === 'adminradiosynapse@gmail.com' || fallbackEmail === 'admin@radiosynapse.fr';
      matchedUser = {
        id: storedUser?.id || `usr_passkey_${Date.now()}`,
        email: fallbackEmail,
        username: storedUser?.username || fallbackEmail.split('@')[0],
        firstName: storedUser?.firstName,
        lastName: storedUser?.lastName,
        displayName: storedUser?.displayName || storedUser?.username || fallbackEmail.split('@')[0],
        role: isSuper ? 'super-admin' : 'user',
        adminProfileId: isSuper ? 'profile_super_admin' : 'profile_animateur',
        assignedStationId: 'all',
        avatarUrl: storedUser?.avatarUrl || `https://api.dicebear.com/7.x/bottts/svg?seed=${encodeURIComponent(fallbackEmail)}`,
        createdAt: Date.now(),
        points: storedUser?.points ?? 150,
        badges: storedUser?.badges || ['Passkey Sécurisée'],
        authMethod: 'passkey',
        passkeyCredentialId: usedCredentialId,
      };
    }

    // Save active session
    saveStoredSynapseUser(matchedUser);

    return {
      success: true,
      user: matchedUser,
      message: `Connexion par Passkey réussie ! Bienvenue, ${matchedUser.displayName || matchedUser.username}.`,
    };
  } catch (err: any) {
    console.error('Passkey authentication error:', err);
    if (err.name === 'NotAllowedError') {
      return { success: false, message: 'Authentification Passkey refusée ou annulée.' };
    }
    return {
      success: false,
      message: err?.message || 'Erreur lors de la validation de la Passkey.',
      error: err?.message,
    };
  }
}
